-- ============================================================
-- 2. CHATBOT TELEMETRY TABLE
-- ============================================================

DROP TABLE IF EXISTS chatbot_telemetry CASCADE;

CREATE TABLE chatbot_telemetry (
  -- Primary key
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  
  -- Run identifier (unique per request)
  run_id UUID NOT NULL UNIQUE,
  
  -- User context
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  session_id TEXT,
  
  -- Timestamp (with timezone)
  timestamp TIMESTAMPTZ DEFAULT NOW(),
  
  -- Prompt tracking
  prompt_id TEXT NOT NULL DEFAULT 'chef_cei_v1.2',
  prompt_hash TEXT NOT NULL,  -- Full SHA-256: sha256:<64-hex-chars>
  
  -- Model info
  model_name TEXT DEFAULT 'gemini-3-flash-preview',
  model_version TEXT,
  
  -- Generation config
  temperature FLOAT DEFAULT 0.4,
  max_tokens INTEGER DEFAULT 1024,
  top_p FLOAT DEFAULT 0.95,
  
  -- Token usage (JSONB for flexibility)
  -- Format: {"input_tokens": 120, "output_tokens": 432, "total_tokens": 552}
  token_usage JSONB,
  
  -- Performance metrics
  latency_ms INTEGER,
  http_status INTEGER,
  response_truncated BOOLEAN DEFAULT false,
  
  -- Safety tracking
  safety_flag BOOLEAN DEFAULT false,
  safety_reasons TEXT[] DEFAULT '{}',
  post_processing_actions TEXT[] DEFAULT '{}',
  
  -- Response storage
  response_pointer TEXT,  -- e.g., supabase_storage://bucket/responses/uuid.txt
  response_text TEXT,     -- Inline storage if no bucket available (nullable)

  -- RAG / vignette metadata
  query_text TEXT,
  scenario_id TEXT,
  reference_answer TEXT,
  ground_truth_document TEXT,
  ground_truth_chunk_idx JSONB,

  -- RAG observability fields
  rag_mode TEXT,
  rag_documents_retrieved INTEGER DEFAULT 0,
  rag_retrieval_latency_ms INTEGER,
  reranker_latency_ms INTEGER,
  reranker_scores JSONB,
  retrieved_results JSONB,

  -- Token usage breakdown (flattened convenience fields)
  token_usage_input INTEGER,
  token_usage_output INTEGER,
  
  -- Metadata
  edge_function_version TEXT,
  app_version TEXT,
  region TEXT DEFAULT 'asia-southeast1'
);

-- Add comments for documentation
COMMENT ON TABLE chatbot_telemetry IS 'LLMOps telemetry for chatbot requests';
COMMENT ON COLUMN chatbot_telemetry.run_id IS 'Unique UUID v4 per request, generated by Edge Function';
COMMENT ON COLUMN chatbot_telemetry.prompt_hash IS 'Full SHA-256 hash of system prompt, format: sha256:<64-hex>';
COMMENT ON COLUMN chatbot_telemetry.token_usage IS 'JSONB: {input_tokens, output_tokens, total_tokens}';
COMMENT ON COLUMN chatbot_telemetry.safety_flag IS 'True if response was flagged for safety review';
COMMENT ON COLUMN chatbot_telemetry.response_pointer IS 'Storage path if response uploaded to bucket';
COMMENT ON COLUMN chatbot_telemetry.response_text IS 'Inline response text if storage unavailable';

