CREATE INDEX idx_telemetry_run_id ON chatbot_telemetry(run_id);
CREATE INDEX idx_telemetry_user_id ON chatbot_telemetry(user_id);
CREATE INDEX idx_telemetry_timestamp ON chatbot_telemetry(timestamp DESC);
CREATE INDEX idx_telemetry_safety_flag ON chatbot_telemetry(safety_flag) WHERE safety_flag = true;
CREATE INDEX idx_telemetry_prompt_hash ON chatbot_telemetry(prompt_hash);
CREATE INDEX idx_telemetry_http_status ON chatbot_telemetry(http_status);

-- ============================================================
-- 4. REVIEW QUEUE TABLE
-- ============================================================

DROP TABLE IF EXISTS review_queue CASCADE;

CREATE TABLE review_queue (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  
  -- Reference to telemetry
  run_id UUID REFERENCES chatbot_telemetry(run_id) ON DELETE CASCADE,
  
  -- Flag info
  flag_reason TEXT NOT NULL,
  priority INTEGER DEFAULT 1 CHECK (priority BETWEEN 1 AND 3),
  -- 1 = low (allergy warning), 2 = medium (blocked content), 3 = high (API error)
  
  -- Review status
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'approved', 'rejected')),
  
  -- Assignment & Review
  assigned_to UUID REFERENCES auth.users(id),
  reviewer_id UUID REFERENCES auth.users(id),
  reviewer_decision TEXT,  -- 'approve', 'reject', 'escalate'
  reviewer_comments TEXT,
  
  -- Timestamps
  created_at TIMESTAMPTZ DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ
);

COMMENT ON TABLE review_queue IS 'Human-in-the-loop review queue for flagged chatbot responses';
COMMENT ON COLUMN review_queue.priority IS '1=low, 2=medium, 3=high';
COMMENT ON COLUMN review_queue.status IS 'pending, in_progress, approved, rejected';

-- ============================================================
-- 5. INDEXES FOR REVIEW QUEUE
-- ============================================================

CREATE INDEX idx_review_run_id ON review_queue(run_id);
CREATE INDEX idx_review_status ON review_queue(status);
CREATE INDEX idx_review_priority ON review_queue(priority DESC);
CREATE INDEX idx_review_created_at ON review_queue(created_at DESC);
CREATE INDEX idx_review_pending ON review_queue(status, priority DESC) WHERE status = 'pending';

-- ============================================================
-- 6. METRICS VIEW (for observability dashboard)
-- ============================================================

CREATE OR REPLACE VIEW chatbot_metrics_daily AS
SELECT 
  DATE_TRUNC('day', timestamp) as date,
  COUNT(*) as total_requests,
  COUNT(*) FILTER (WHERE safety_flag = true) as flagged_count,
  ROUND(100.0 * COUNT(*) FILTER (WHERE safety_flag = false) / NULLIF(COUNT(*), 0), 2) as safety_pass_rate,
  ROUND(AVG(latency_ms)::numeric, 2) as avg_latency_ms,
  PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY latency_ms) as p50_latency_ms,
  PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY latency_ms) as p95_latency_ms,
  PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY latency_ms) as p99_latency_ms,
  ROUND(AVG((token_usage->>'total_tokens')::int)::numeric, 2) as avg_tokens,
  COUNT(*) FILTER (WHERE http_status != 200) as error_count,
  ROUND(100.0 * COUNT(*) FILTER (WHERE http_status != 200) / NULLIF(COUNT(*), 0), 2) as error_rate,
  COUNT(*) FILTER (WHERE response_truncated = true) as truncated_count
FROM chatbot_telemetry
WHERE timestamp > NOW() - INTERVAL '30 days'
GROUP BY DATE_TRUNC('day', timestamp)
ORDER BY date DESC;

COMMENT ON VIEW chatbot_metrics_daily IS 'Daily aggregated metrics for observability dashboard';

-- ============================================================
-- 7. HELPER FUNCTION: Get pending reviews count
-- ============================================================

CREATE OR REPLACE FUNCTION get_pending_reviews_count()
RETURNS TABLE (
  priority INTEGER,
  count BIGINT
) AS $$
BEGIN
  RETURN QUERY
  SELECT rq.priority, COUNT(*)
  FROM review_queue rq
  WHERE rq.status = 'pending'
  GROUP BY rq.priority
  ORDER BY rq.priority DESC;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- 8. HELPER FUNCTION: Claim review
-- ============================================================

CREATE OR REPLACE FUNCTION claim_review(
  p_review_id UUID,
  p_reviewer_id UUID
) RETURNS BOOLEAN AS $$
DECLARE
  v_updated BOOLEAN;
BEGIN
  UPDATE review_queue
  SET 
    status = 'in_progress',
    assigned_to = p_reviewer_id
  WHERE id = p_review_id
    AND status = 'pending';
  
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  RETURN v_updated > 0;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- 9. HELPER FUNCTION: Complete review
-- ============================================================

CREATE OR REPLACE FUNCTION complete_review(
  p_review_id UUID,
  p_reviewer_id UUID,
  p_decision TEXT,
  p_comments TEXT DEFAULT NULL
) RETURNS BOOLEAN AS $$
DECLARE
  v_updated BOOLEAN;
BEGIN
  UPDATE review_queue
  SET 
    status = CASE WHEN p_decision = 'approve' THEN 'approved' ELSE 'rejected' END,
    reviewer_id = p_reviewer_id,
    reviewer_decision = p_decision,
    reviewer_comments = p_comments,
    reviewed_at = NOW()
  WHERE id = p_review_id
    AND status = 'in_progress';
  
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  RETURN v_updated > 0;
END;
$$ LANGUAGE plpgsql;

